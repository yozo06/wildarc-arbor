// Writes supabase/seed.sql from the phone version's sample farm (frontend/src/core/data/local/sample-farm.json),
// so the server version starts with the same made-up "Sample Food Forest". Deterministic: same input, same file.
// Run from the repository root: node scripts/make-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import bcrypt from 'bcryptjs'

const at = path => fileURLToPath(new URL(`../${path}`, import.meta.url))
const farm = JSON.parse(readFileSync(at('frontend/src/core/data/local/sample-farm.json'), 'utf8'))

// The local owner's sign-in. For a database on your own computer only; documented in .env.example and the README.
const OWNER_EMAIL = 'owner@example.com'
const OWNER_PASSWORD = 'arbor-local-only'
const FIXED_SALT = '$2a$10$arborlocalonlysaltsalt' // fixed so the file does not change on every run

const lit = v => v === null || v === undefined ? 'null'
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : `'${String(v).replace(/'/g, "''")}'`
const json = v => v === null || v === undefined ? 'null' : `${lit(JSON.stringify(v))}::jsonb`

function insert(table, columns, rows) {
  if (!rows.length) return ''
  const values = rows.map(r => `  (${columns.map(c => r[c]).join(', ')})`).join(',\n')
  return `insert into public.${table} (${columns.join(', ')}) values\n${values};\n\n`
}

const treeId = new Map(farm.trees.map(t => [t.tree_code, t.id]))
const out = [
  '-- Generated by scripts/make-seed.mjs from frontend/src/core/data/local/sample-farm.json. Do not edit by hand.',
  '-- "Sample Food Forest" is made up. The owner sign-in below is for a database on your own computer only:',
  `--   ${OWNER_EMAIL} / ${OWNER_PASSWORD}`,
  '',
  insert('users', ['id', 'name', 'email', 'password_hash', 'role'], [{
    id: 1, name: lit('Sample Owner'), email: lit(OWNER_EMAIL), password_hash: lit(bcrypt.hashSync(OWNER_PASSWORD, FIXED_SALT)), role: lit('owner'),
  }]),
  insert('land_zones', ['id', 'zone_code', 'zone_name', 'description', 'boundary_coords'], farm.zones.map(z => ({
    id: z.id, zone_code: lit(z.zone_code), zone_name: lit(z.zone_name), description: lit(z.description), boundary_coords: json(z.boundary_coords),
  }))),
  insert('species', ['id', 'common_name', 'scientific_name', 'description', 'fun_fact'], farm.species.map(s => ({
    id: s.id, common_name: lit(s.common_name), scientific_name: lit(s.scientific_name), description: lit(s.description), fun_fact: lit(s.fun_fact),
  }))),
  insert('trees', [
    'id', 'tree_code', 'species_id', 'zone_id', 'custom_common_name', 'health_score', 'action', 'status', 'priority',
    'coord_x', 'coord_y', 'approx_age_yrs', 'height_m', 'trunk_diameter_cm', 'planting_date', 'added_by',
    'completed_at', 'created_at', 'updated_at',
  ], farm.trees.map(t => ({
    id: t.id, tree_code: lit(t.tree_code), species_id: lit(t.species_id), zone_id: lit(t.zone_id),
    custom_common_name: lit(t.custom_common_name), health_score: lit(t.health_score), action: lit(t.action),
    status: lit(t.status), priority: lit(t.priority), coord_x: lit(t.coord_x), coord_y: lit(t.coord_y),
    approx_age_yrs: lit(t.approx_age_yrs), height_m: lit(t.height_m), trunk_diameter_cm: lit(t.trunk_diameter_cm),
    planting_date: lit(t.planting_date), added_by: 1, completed_at: lit(t.completed_at), created_at: lit(t.created_at),
    updated_at: lit(t.updated_at),
  }))),
  insert('tree_health_observations', [
    'id', 'tree_id', 'observed_by', 'observed_at', 'health_score', 'leaf_color', 'bark_condition', 'pest_presence',
    'disease_signs', 'height_m', 'additional_notes',
  ], farm.health.map(h => ({
    id: h.id, tree_id: treeId.get(h.tree_code), observed_by: 1, observed_at: lit(h.observed_at), health_score: lit(h.health_score),
    leaf_color: lit(h.leaf_color), bark_condition: lit(h.bark_condition), pest_presence: lit(h.pest_presence),
    disease_signs: lit(h.disease_signs), height_m: lit(h.height_m), additional_notes: lit(h.additional_notes),
  }))),
  insert('tree_activity_log', ['id', 'tree_id', 'performed_by', 'action_taken', 'previous_status', 'new_status', 'notes', 'logged_at'],
    farm.activity.map(a => ({
      id: a.id, tree_id: treeId.get(a.tree_code), performed_by: 1, action_taken: lit(a.action_taken),
      previous_status: lit(a.previous_status), new_status: lit(a.new_status), notes: lit(a.notes), logged_at: lit(a.logged_at),
    }))),
  '-- The rows above set their own ids; move each id counter past them so new rows do not collide.',
  ...['users', 'land_zones', 'species', 'trees', 'tree_health_observations', 'tree_activity_log'].map(t =>
    `select setval(pg_get_serial_sequence('public.${t}', 'id'), (select max(id) from public.${t}));`),
  '',
].join('\n')

writeFileSync(at('supabase/seed.sql'), out)
console.log(`wrote supabase/seed.sql: ${farm.trees.length} trees, ${farm.zones.length} zones, ${farm.species.length} species`)
