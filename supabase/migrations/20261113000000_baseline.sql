-- Arbor, server version: the whole database in one file.
--
-- Rebuilt in November 2026 from what the API reads and writes (src/modules/*/routes) and from the older files in
-- docs/migrations. The first live database was made by hand in Supabase Studio and never written down, so this is
-- a reconstruction: if a dump of a live project ever becomes available, compare the two and keep the dump.
--
-- Security: the API talks to the database with the service key, which bypasses row-level security. Every table
-- below turns row-level security on and adds no policies, so the public (anon) key that Supabase hands out can
-- read and write nothing.

-- People who sign in to the server version.
create table public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'employee' check (role in ('owner', 'employee', 'volunteer')),
  phone text,
  bio text,
  profile_photo text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Farms ("projects") and who works on them (docs/migrations/002). Not yet read by the API's tree routes.
create table public.projects (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  owner_id bigint references public.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create type public.project_role as enum ('admin', 'editor', 'contributor', 'viewer');

create table public.project_members (
  project_id uuid references public.projects (id) on delete cascade,
  user_id bigint references public.users (id) on delete cascade,
  role public.project_role not null default 'viewer',
  created_at timestamptz not null default now(),
  primary key (project_id, user_id)
);

-- Parts of the land. boundary_coords is a list of [x, y] points in metres, as the Land Map reads it.
create table public.land_zones (
  id bigint generated by default as identity primary key,
  zone_code text not null unique,
  zone_name text not null,
  description text,
  boundary_coords jsonb,
  project_id uuid references public.projects (id) on delete cascade
);

create table public.ecosystem_roles (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text,
  description text
);

create table public.species (
  id bigint generated by default as identity primary key,
  common_name text not null,
  scientific_name text,
  description text,
  fun_fact text,
  edible_parts text,
  medicinal_uses text,
  ecosystem_roles text[],
  water_needs text,
  sunlight_needs text,
  is_native boolean,
  external_ref_url text,
  reference_images text[],
  image_url text
);

-- One row per tree. Coordinates and sizes are metres; the choices match what the screens offer.
create table public.trees (
  id bigint generated by default as identity primary key,
  tree_code text not null unique,
  species_id bigint references public.species (id) on delete set null,
  zone_id bigint references public.land_zones (id) on delete set null,
  project_id uuid references public.projects (id) on delete cascade,
  custom_common_name text,
  custom_fun_fact text,
  health_score smallint check (health_score between 1 and 10),
  action text not null default 'pending'
    check (action in ('pending', 'cut', 'trim', 'keep', 'monitor', 'treat', 'replant')),
  status text not null default 'pending' check (status in ('pending', 'in_progress', 'completed', 'on_hold')),
  priority text not null default 'medium' check (priority in ('low', 'medium', 'high', 'urgent')),
  coord_x double precision,
  coord_y double precision,
  approx_age_yrs double precision,
  height_m double precision,
  trunk_diameter_cm double precision,
  action_notes text,
  public_notes text,
  decision_factors jsonb,
  planting_date date,
  assigned_to bigint references public.users (id) on delete set null,
  added_by bigint references public.users (id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create function public.set_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end
$$;

create trigger trees_updated_at before update on public.trees
  for each row execute function public.set_updated_at();

-- A tree's work log: created, status changes, photos added, and what people did.
create table public.tree_activity_log (
  id bigint generated by default as identity primary key,
  tree_id bigint not null references public.trees (id) on delete cascade,
  performed_by bigint references public.users (id) on delete set null,
  action_taken text not null,
  previous_status text,
  new_status text,
  notes text,
  logged_at timestamptz not null default now()
);
create index tree_activity_log_by_tree on public.tree_activity_log (tree_id, logged_at desc);

-- Health observations. The columns after `notes` are what the health form sends.
create table public.tree_health_observations (
  id bigint generated by default as identity primary key,
  tree_id bigint not null references public.trees (id) on delete cascade,
  observed_by bigint references public.users (id) on delete set null,
  observed_at timestamptz not null default now(),
  health_score smallint not null check (health_score between 1 and 10),
  observed_issues text,
  notes text,
  leaf_color text,
  bark_condition text,
  pest_presence boolean,
  disease_signs boolean,
  height_m double precision,
  additional_notes text
);
create index tree_health_observations_by_tree on public.tree_health_observations (tree_id, observed_at desc);

-- Photos are stored elsewhere (Google Drive in the server version); this keeps their address.
create table public.tree_photos (
  id bigint generated by default as identity primary key,
  tree_id bigint not null references public.trees (id) on delete cascade,
  uploaded_by bigint references public.users (id) on delete set null,
  photo_url text not null,
  photo_type text not null default 'general',
  caption text,
  taken_at timestamptz not null default now()
);
create index tree_photos_by_tree on public.tree_photos (tree_id, taken_at desc);

create table public.tree_contributors (
  id bigint generated by default as identity primary key,
  tree_id bigint not null references public.trees (id) on delete cascade,
  user_id bigint not null references public.users (id) on delete cascade,
  role text not null,
  since_date date,
  notes text,
  is_public boolean not null default true
);

-- Counts per zone, as the dashboard and the zone list read them (docs/migrations/008).
create view public.zone_summary as
select
  lz.id,
  lz.zone_code,
  lz.zone_name,
  lz.project_id,
  count(t.id)::int as total_trees,
  (count(t.id) filter (where t.status = 'completed'))::int as completed
from public.land_zones lz
left join public.trees t on t.zone_id = lz.id
group by lz.id, lz.zone_code, lz.zone_name, lz.project_id;

-- What the Land Map plots: one row per tree, named by its own name, its species, or its code.
create view public.map_tree_view as
select
  t.id,
  t.tree_code,
  t.action,
  t.status,
  t.coord_x,
  t.coord_y,
  coalesce(t.custom_common_name, s.common_name, t.tree_code) as display_name,
  z.zone_code,
  t.health_score,
  t.height_m,
  t.project_id
from public.trees t
left join public.species s on s.id = t.species_id
left join public.land_zones z on z.id = t.zone_id;

-- Row-level security on, no policies: only the service key (the API) gets through.
alter table public.users enable row level security;
alter table public.projects enable row level security;
alter table public.project_members enable row level security;
alter table public.land_zones enable row level security;
alter table public.ecosystem_roles enable row level security;
alter table public.species enable row level security;
alter table public.trees enable row level security;
alter table public.tree_activity_log enable row level security;
alter table public.tree_health_observations enable row level security;
alter table public.tree_photos enable row level security;
alter table public.tree_contributors enable row level security;

-- The views run with the rights of whoever reads them, so they cannot be used to get round the rules above.
alter view public.zone_summary set (security_invoker = true);
alter view public.map_tree_view set (security_invoker = true);

-- Supabase's service role gets everything. Skipped where that role does not exist (plain Postgres, tests).
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant all on all tables in schema public to service_role;
    grant usage, select on all sequences in schema public to service_role;
  end if;
end
$$;
